    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    public static function find(int $id): ?array
    {
        foreach (static::all() as $p) {
            if ($p['id'] === $id) {
                return $p;
            }
        }

        return null;
    }

    public static function enrich(array $p): array
    {
        $dob = Carbon::parse($p['date_of_birth']);
        $p['age'] = $dob->age;
        $p['full_name'] = trim(
            $p['first_name'].' '.
            ($p['middle_name'] ? $p['middle_name'].' ' : '').
            $p['last_name']
        );
        $p['initials'] = strtoupper(
            substr($p['first_name'], 0, 1).
            substr($p['last_name'], 0, 1)
        );

        return $p;
    }

    public static function summaryCounts(): array
    {
        $all = static::all();

        return [
            'total' => count($all),
            'active' => count(array_filter($all, fn ($p) => $p['employment_status'] === 'Active')),
            'assigned' => count(array_filter($all, fn ($p) => $p['facility_id'] !== null)),
            'unassigned' => count(array_filter($all, fn ($p) => $p['facility_id'] === null)),
        ];
    }

    /** Personnel for a specific facility ID. */
    public static function forFacility(int $facilityId): array
    {
        return array_values(array_filter(
            static::all(),
            fn ($p) => $p['facility_id'] === $facilityId
        ));
    }

    /** Activity timeline for a personnel record. */
    public static function activityTimeline(int $personnelId): array
    {
        $p = static::find($personnelId);
        if (! $p) {
            return [];
        }

        return [
            [
                'event' => 'Record Created',
                'detail' => 'Personnel record created in the Prison Management System.',
                'timestamp' => $p['created_date'].' 09:00',
                'type' => 'system',
                'actor' => 'System Administrator',
            ],
            [
                'event' => 'Appointment Recorded',
                'detail' => 'Appointed as '.$p['rank'].', '.$p['department'].' department.',
                'timestamp' => $p['appointment_date'].' 10:00',
                'type' => 'admission',
                'actor' => 'Human Resources (demo role)',
            ],
            [
                'event' => 'Facility Assignment',
                'detail' => $p['facility']
                    ? 'Assigned to '.$p['facility'].'.'
                    : 'Assigned to headquarters — no specific facility.',
                'timestamp' => $p['appointment_date'].' 11:30',
                'type' => 'transfer',
                'actor' => 'Human Resources (demo role)',
            ],
        ];
    }
