    public static function find(int $id): ?array
    {
        foreach (static::all() as $a) {
            if ($a['id'] === $id) {
                return $a;
            }
        }

        return null;
    }

    public static function forPersonnel(int $personnelId): array
    {
        return array_values(array_filter(
            static::all(),
            fn ($a) => $a['personnel_id'] === $personnelId
        ));
    }

    public static function forFacility(int $facilityId): array
    {
        return array_values(array_filter(
            static::all(),
            fn ($a) => $a['facility_id'] === $facilityId && $a['status'] === 'Active'
        ));
    }

    public static function active(): array
    {
        return array_values(array_filter(
            static::all(),
            fn ($a) => $a['status'] === 'Active'
        ));
    }

    public static function summaryCounts(): array
    {
        $all = static::all();

        return [
            'total' => count($all),
            'active' => count(array_filter($all, fn ($a) => $a['status'] === 'Active')),
            'completed' => count(array_filter($all, fn ($a) => $a['status'] === 'Completed')),
            'suspended' => count(array_filter($all, fn ($a) => $a['status'] === 'Suspended')),
        ];
    }
